// C0: the host probe. One honest GET per URL, never retried; a host's first 403 ends its probe.
import { describe, expect, it } from "vitest";
import { HOSTS, probeHost, probeOne, probeUrls, toMarkdown } from "../scripts/capture/probe-hosts.mjs";
import { USER_AGENT, refusalKind } from "../scripts/lib/rights/http.mjs";

type Call = { url: string; ua: string };

function fakeFetch(answers: Record<string, () => Response>) {
  const calls: Call[] = [];
  const impl = async (url: string, init: { headers: Record<string, string> }) => {
    calls.push({ url, ua: init.headers["user-agent"] });
    const a = answers[url];
    if (!a) return new Response("nope", { status: 404 });
    return a();
  };
  return { impl, calls };
}

describe("probe-hosts", () => {
  it("lists the design's 11 hosts, each probed robots, feed, home in that order", () => {
    expect(HOSTS).toHaveLength(11);
    expect(new Set(HOSTS.map((h) => h.host)).size).toBe(11);
    const u = probeUrls({ host: "www.noaa.gov", feed: "https://www.noaa.gov/rss.xml" });
    expect(u.map((x) => x.kind)).toEqual(["robots", "feed", "home"]);
    expect(u[0].url).toBe("https://www.noaa.gov/robots.txt");
  });

  it("sends the honest user agent and stops a host at its first 403, asking nothing more", async () => {
    const { impl, calls } = fakeFetch({
      "https://www.noaa.gov/robots.txt": () => new Response("User-agent: *", { status: 200, headers: { server: "CloudFront" } }),
      "https://www.noaa.gov/rss.xml": () => new Response("Generated by cloudfront (CloudFront)", { status: 403, headers: { server: "CloudFront" } }),
    });
    const r = await probeHost({ host: "www.noaa.gov", feed: "https://www.noaa.gov/rss.xml" }, { fetchImpl: impl as never });
    expect(r.refused).toBe(true);
    expect(calls).toHaveLength(2);
    expect(calls.every((c) => c.ua === USER_AGENT)).toBe(true);
    expect(r.rows[1]).toMatchObject({ status: 403, refusal_kind: 'CloudFront "Request blocked"' });
    expect(r.rows[2]).toMatchObject({ kind: "home", skipped: expect.stringMatching(/not asked/) });
  });

  it("never retries a 5xx or a network error", async () => {
    let n = 0;
    const impl = async () => {
      n++;
      return new Response("busy", { status: 503 });
    };
    const r = await probeOne("https://www.state.gov/robots.txt", { fetchImpl: impl as never });
    expect(r.status).toBe(503);
    expect(n).toBe(1);
    let m = 0;
    const boom = async () => {
      m++;
      throw new Error("ECONNRESET");
    };
    const e = await probeOne("https://www.state.gov/", { fetchImpl: boom as never });
    expect(e).toMatchObject({ status: null, error: "ECONNRESET" });
    expect(m).toBe(1);
  });

  it("follows a same-host redirect by hand and refuses to follow one off the host", async () => {
    const { impl, calls } = fakeFetch({
      "https://www.war.gov/": () => new Response(null, { status: 301, headers: { location: "/Home/" } }),
      "https://www.war.gov/Home/": () => new Response("ok", { status: 200 }),
      "https://www.state.gov/": () => new Response(null, { status: 302, headers: { location: "https://elsewhere.example/" } }),
    });
    const a = await probeOne("https://www.war.gov/", { fetchImpl: impl as never });
    expect(a).toMatchObject({ status: 200, final_url: "https://www.war.gov/Home/" });
    const b = await probeOne("https://www.state.gov/", { fetchImpl: impl as never });
    expect(b.error).toMatch(/off host/);
    expect(calls.map((c) => c.url)).not.toContain("https://elsewhere.example/");
  });

  it("names a CloudFront block and renders the table", () => {
    expect(refusalKind("CloudFront", "Request blocked")).toMatch(/CloudFront/);
    const md = toMarkdown([{ host: "www.noaa.gov", refused: true, rows: [
      { kind: "robots", status: 200, server: "CloudFront", refusal_kind: null, error: null },
      { kind: "feed", status: 403, server: "CloudFront", refusal_kind: 'CloudFront "Request blocked"', error: null },
      { kind: "home", status: null, skipped: "not asked" },
    ] }] as never, { at: "2026-11-13T18:00:00Z", where: "test" });
    expect(md).toContain('| www.noaa.gov | 200 | 403 (CloudFront "Request blocked") | not asked | CloudFront | yes |');
  });
});
