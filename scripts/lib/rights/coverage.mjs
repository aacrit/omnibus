// The episode's asset coverage table (episodes/<issue>/ASSETS.md), generated
// from assets.json and the rights ledger by `node scripts/rights.mjs coverage`:
// each request's item or fallback, its tier and licence, seconds of footage
// or sound, and where the file sits on the media drive. Net-new. Pure: the
// durations are measured by the caller (ffprobe) and passed in.

import { licenceName } from "./licences.mjs";

/** A value made safe for one Markdown table cell: no pipes, no tags, no line breaks. */
export function cell(v) {
  return String(v ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\|/g, "\\|")
    .replace(/[\r\n]+/g, " ")
    .trim();
}

function clipped(s, n) {
  const t = String(s ?? "");
  return t.length > n ? `${t.slice(0, n - 3)}...` : t;
}

/** The rundown part a request's `for` belongs to. */
export function partOf(forId) {
  const f = String(forId ?? "");
  if (f === "cold-open") return "Cold open";
  if (f === "title") return "Title";
  if (f.startsWith("week-")) return "The Week";
  if (f.startsWith("weight-")) return "The Weight";
  if (f.startsWith("echo")) return "The Echo";
  if (f.startsWith("margins-")) return "The Margins";
  if (f === "all-parts") return "All parts";
  return f || "(none)";
}

export const PARTS = ["Cold open", "Title", "The Week", "The Weight", "The Echo", "The Margins", "All parts"];
const PICTURE = new Set(["still", "footage"]);
const fmt = (s) => (s == null ? "-" : `${s.toFixed(1)} s`);

/**
 * Pure: the coverage page. durations maps a ledger file name to its length
 * in seconds (footage and sound only); mediaDir is printed as given.
 */
export function buildCoverage({ assets, ledger, durations = {}, mediaDir }) {
  const items = new Map(ledger.items.map((i) => [i.request_id, i]));
  const drops = new Map((ledger.dropped ?? []).map((d) => [d.request_id, d]));
  const rows = [];
  const byPart = new Map(PARTS.map((p) => [p, { requests: 0, pictures: 0, fetched: 0, footage: 0, stills: 0, sound: 0, toTier4: 0 }]));
  const tally = { satisfied: {}, dropped: {} };
  for (const r of assets.requests) {
    const part = partOf(r.for);
    const p = byPart.get(part) ?? byPart.set(part, { requests: 0, pictures: 0, fetched: 0, footage: 0, stills: 0, sound: 0, toTier4: 0 }).get(part);
    p.requests++;
    if (PICTURE.has(r.kind)) p.pictures++;
    const it = items.get(r.id);
    if (it) {
      // A still filling a footage request is a rostrum still: it adds no seconds of footage.
      const stillForFootage = r.kind === "footage" && /^image\//.test(String(it.mime ?? ""));
      const secs = stillForFootage ? null : (durations[it.file] ?? null);
      if (r.kind === "footage") p.footage += secs ?? 0;
      if (r.kind === "sound") p.sound += secs ?? 0;
      if (PICTURE.has(r.kind)) p.fetched++;
      if (PICTURE.has(r.kind) && (r.kind === "still" || stillForFootage)) p.stills++;
      tally.satisfied[it.source_tier] = (tally.satisfied[it.source_tier] ?? 0) + 1;
      rows.push([r.id, part, r.kind, `${clipped(it.title, 90)} (${it.adapter})${stillForFootage ? ", a still filling a footage request (rostrum)" : ""}`, it.source_tier, licenceName(it.licence), stillForFootage ? "still" : r.kind === "footage" || r.kind === "sound" ? fmt(secs) : "-", `${mediaDir}/${it.file}`]);
    } else {
      const d = drops.get(r.id);
      const tier = d?.fallback_tier ?? r.fallback?.tier ?? null;
      if (tier === 4 && PICTURE.has(r.kind)) p.toTier4++;
      const key = tier ?? "none";
      tally.dropped[key] = (tally.dropped[key] ?? 0) + 1;
      rows.push([r.id, part, r.kind, `fallback: ${clipped(d?.fallback ?? r.fallback?.text ?? "none stated", 140)}`, tier ?? "-", "-", "-", "-"]);
    }
  }
  const sat = Object.values(tally.satisfied).reduce((a, b) => a + b, 0);
  const drp = Object.values(tally.dropped).reduce((a, b) => a + b, 0);
  const tierList = (o) => Object.keys(o).sort().map((k) => `${k === "none" ? "no fallback" : `tier ${k}`} ${o[k]}`).join(", ") || "none";
  const thin = [...byPart.entries()].filter(([, v]) => v.pictures > 0 && v.footage === 0 && v.fetched * 2 < v.pictures);
  const out = [];
  out.push(`# Week ${ledger.issue} assets`, "");
  out.push(
    `Generated by \`node scripts/rights.mjs coverage ${ledger.issue} --media <dir>\` from \`assets.json\` and \`rights-ledger.json\`; never edited by hand. Every item passed the fetcher's licence, evidence, denylist, AI-provenance, laundering and date-window checks; the vision pass (stage 9) has not run, so each item's vision check is pending.`,
    "",
  );
  out.push(`${assets.requests.length} requests: ${sat} satisfied (${tierList(tally.satisfied)}), ${drp} dropped to their fallback (${tierList(tally.dropped)}). Media under \`${cell(mediaDir)}\`, outside the repo.`, "");
  out.push("## By part", "", "| Part | Requests | Picture requests | Pictures fetched | Pictures to tier 4 | Footage | Stills | Sound |", "|---|---|---|---|---|---|---|---|");
  for (const [k, v] of byPart) {
    if (!v.requests) continue;
    out.push(`| ${cell(k)} | ${v.requests} | ${v.pictures} | ${v.fetched} | ${v.toTier4} | ${fmt(v.footage)} | ${v.stills} | ${fmt(v.sound)} |`);
  }
  out.push("");
  out.push(
    thin.length
      ? `Thin pictures (no footage, and under half the picture requests fetched): ${thin.map(([k, v]) => `${k} (${v.fetched} of ${v.pictures})`).join("; ")}.`
      : "No part is thin by the rule (no footage, and under half the picture requests fetched).",
    "",
  );
  out.push("## Coverage", "", "| Request | Part | Kind | Item or fallback | Tier | Licence | Seconds | File |", "|---|---|---|---|---|---|---|---|");
  for (const row of rows) out.push(`| ${row.map(cell).join(" | ")} |`);
  out.push("", "## Footage fit", "", "Why each footage item shows its beat, the seconds that show it, and its publication time against the beat's horizon (from the sourcing pass's pin).", "");
  const fits = ledger.items.filter((i) => i.fit);
  if (!fits.length) out.push("No item records a fit yet.");
  for (const i of fits) {
    const span = Number.isFinite(i.fit.in_s) && Number.isFinite(i.fit.out_s) ? `${i.fit.in_s.toFixed(1)} to ${i.fit.out_s.toFixed(1)} s` : "whole item";
    // A dot label the shot must carry (ruling A's FILMED/PUBLISHED line, or a sourcing pass's).
    const dot = i.dot_label?.text ? `; dot label "${cell(i.dot_label.text)}"${i.published_by_edition ? " (picture_published_by_edition)" : ""}` : "";
    out.push(`- **${cell(i.request_id)}** (${cell(i.fit.beat)}), ${span}; published ${cell(i.published_at ?? "-")}${i.fit.horizon ? `, horizon ${cell(i.fit.horizon)}` : ""}${dot}: ${cell(clipped(i.fit.why, 400))}`);
  }
  out.push("", "## Why each drop", "");
  for (const d of ledger.dropped ?? []) {
    out.push(`- **${cell(d.request_id)}** (to ${d.fallback_tier ? `tier ${d.fallback_tier}` : "no fallback tier"}):`);
    for (const reason of d.reasons) out.push(`  - ${cell(clipped(reason, 400))}`);
  }
  out.push("", "## Date witnesses", "", "Wayback captures read as date witnesses only, never as a licence.", "");
  if (!(ledger.witnesses ?? []).length) out.push("No Wayback capture was read.");
  for (const w of ledger.witnesses ?? []) {
    out.push(
      `- ${cell(w.request_id)}: ${cell(w.original_url)}, captured ${cell(w.captured_at)}${w.sha256 ? `, sha256 ${w.sha256}, file ${cell(`${mediaDir}/${w.file}`)}` : ", not downloaded"}; ${w.used ? "used" : "not an episode asset"}. Text in the capture: "${cell(clipped(w.text, 300))}"`,
    );
  }
  return `${out.join("\n")}\n`;
}
